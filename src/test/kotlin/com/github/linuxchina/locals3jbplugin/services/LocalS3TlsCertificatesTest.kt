package com.github.linuxchina.locals3jbplugin.services

import junit.framework.TestCase
import java.nio.file.Files
import java.time.Instant
import java.time.temporal.ChronoUnit

class LocalS3TlsCertificatesTest : TestCase() {
    private val directory = Files.createTempDirectory("locals3-tls")

    override fun tearDown() {
        directory.toFile().deleteRecursively()
        super.tearDown()
    }

    fun testGeneratesOnceAndReusesCertificate() {
        val first = LocalS3TlsCertificates.loadOrCreate(directory)
        val second = LocalS3TlsCertificates.loadOrCreate(directory)

        assertTrue(Files.isRegularFile(directory.resolve(LocalS3TlsCertificates.CERTIFICATE_FILE)))
        assertTrue(Files.isRegularFile(directory.resolve(LocalS3TlsCertificates.PRIVATE_KEY_FILE)))
        assertEquals(first.certificateChainPem(), second.certificateChainPem())
        assertEquals(first.privateKeyPem(), second.privateKeyPem())
    }

    fun testRenewsGeneratedCertificateBeforeExpiry() {
        val first = LocalS3TlsCertificates.loadOrCreate(directory)
        val nearExpiry = first.certificate().notAfter.toInstant().minus(1, ChronoUnit.DAYS)

        val renewed = LocalS3TlsCertificates.loadOrCreate(directory, nearExpiry)

        assertFalse(first.certificateChainPem() == renewed.certificateChainPem())
        assertEquals(renewed.certificateChainPem(), LocalS3TlsCertificates.loadOrCreate(directory).certificateChainPem())
    }

    fun testKeepsCertificateOfUser() {
        Files.writeString(directory.resolve(LocalS3TlsCertificates.CERTIFICATE_FILE), USER_CERTIFICATE)
        Files.writeString(directory.resolve(LocalS3TlsCertificates.PRIVATE_KEY_FILE), USER_PRIVATE_KEY)

        // Even when it expires soon: the plugin doesn't overwrite a certificate that it didn't generate.
        val loaded = LocalS3TlsCertificates.loadOrCreate(directory, Instant.now().plus(365 * 100, ChronoUnit.DAYS))

        assertEquals(USER_CERTIFICATE, loaded.certificateChainPem())
    }

